export function renderHtml(document: DocumentModel): string {
  const rowsHtml = document.items
    .map(
      (item, index) =>
        `<tr><td>${index + 1}</td><td>${escapeHtml(item)}</td></tr>`,
    )
    .join('\n')

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <style>${documentStyles}</style>
</head>
<body>
  <header class="doc-header">
    <h1 class="doc-title">${escapeHtml(document.title)}</h1>
    <div class="doc-meta">
      <strong>Author:</strong> ${escapeHtml(document.author)}
      &nbsp;&middot;&nbsp;
      <strong>Date:</strong> ${escapeHtml(document.date)}
    </div>
  </header>

  <section>
    <h2 class="doc-section-title">Summary</h2>
    <div class="doc-summary">${escapeHtml(document.summary)}</div>
  </section>

  <section>
    <h2 class="doc-section-title">Items</h2>
    <table>
      <thead>
        <tr><th>#</th><th>Item</th></tr>
      </thead>
      <tbody>
        ${rowsHtml}
      </tbody>
    </table>
  </section>

  <footer class="doc-footer">
    Generated by Document Studio
  </footer>
</body>
</html>`
}
